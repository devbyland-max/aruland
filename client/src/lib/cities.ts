const byName = new Map(DELIVERY_CITIES.map((c) => [c.name, c.country]));

export function citiesFor(country: DeliveryCountry) {
  return DELIVERY_CITIES.filter((c) => c.country === country)
    .map((c) => c.name)
    .sort((a, b) => a.localeCompare(b, "sq"));
}

export function countryForCity(city: string): DeliveryCountry {
  return byName.get(city) ?? "AL";
}
